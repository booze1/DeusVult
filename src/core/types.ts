export type TerrainId =
  | 'OCEAN'
  | 'SHALLOWS'
  | 'BEACH'
  | 'PLAIN'
  | 'FIELD'
  | 'SCRUB'
  | 'FOREST'
  | 'JUNGLE'
  | 'HILL'
  | 'RIDGE'
  | 'MOUNTAIN'
  | 'URBAN'
  | 'AIRFIELD'
  | 'PORT'
  | 'ROAD';

export interface TerrainDef {
  readonly id: TerrainId;
  readonly name: string;
  /** Movement point cost by mobility type; Infinity means impassable. */
  readonly cost: Readonly<Record<MobilityType, number>>;
  /** Elevation in levels; affects line of sight. */
  readonly elevation: number;
  /** How much this tile blocks line of sight through it. */
  readonly losBlock: number;
  /** Reduction to incoming hit probability, 0..1. */
  readonly cover: number;
  /** Reduction to the occupant's visual and thermal signature, 0..1. */
  readonly concealment: number;
  /** Display colour, tactical palette. */
  readonly color: number;
}

export interface MapTile {
  readonly hex: Hex;
  terrain: TerrainId;
  /** Objective marker id, if this tile is an objective. */
  objective?: string;
}

export interface GameMap {
  readonly width: number;
  readonly height: number;
  /** Keyed by hexKey. */
  readonly tiles: Map<number, MapTile>;
}

/* ------------------------------------------------------------------ */
/* Objectives and victory                                              */
/* ------------------------------------------------------------------ */

export type ObjectiveKind =
  | 'CAPTURE'
  | 'DESTROY'
  | 'SURVIVE'
  | 'ESCORT'
  | 'DENY'
  | 'RECON';

export interface Objective {
  readonly id: string;
  readonly kind: ObjectiveKind;
  readonly label: string;
  readonly side: Side;
  /** Hexes involved, for CAPTURE / DENY / RECON. */
  readonly hexes?: readonly Hex[];
  /** Unit ids involved, for DESTROY / ESCORT. */
  readonly unitIds?: readonly UnitId[];
  /**
   * Unit *types* involved, for DESTROY. Preferred over unitIds in authored
   * missions: runtime ids depend on deployment order, so referencing them
   * from content silently breaks the moment a designer reorders the order of
   * battle. "Destroy the landing force" is also what the brief actually says.
   */
  readonly defIds?: readonly UnitDefId[];
  /** Turn deadline, for SURVIVE and timed captures. */
  readonly byTurn?: number;
  /** Optional objectives contribute to score but not to victory. */
  readonly optional: boolean;
  complete: boolean;
  failed: boolean;
}

export type MissionOutcome = 'ONGOING' | 'VICTORY' | 'DEFEAT' | 'DRAW';

/* ------------------------------------------------------------------ */
/* Game state                                                          */
/* ------------------------------------------------------------------ */

export type Phase = 'DEPLOYMENT' | 'BATTLE' | 'RESOLVED';

export interface GameState {
  readonly missionId: string;
  readonly seed: string;
  turn: number;
  maxTurns: number;
  activeSide: Side;
  phase: Phase;
  outcome: MissionOutcome;
  map: GameMap;
  units: Map<UnitId, Unit>;
  /** Per-side belief about enemy units, keyed by observer side. */
  contacts: Record<Side, Map<UnitId, Contact>>;
  /**
   * Laser/data-link designations: enemy unit id -> turn on which the
   * designation lapses. A designated target counts as TRACKED for every
   * shooter on that side, which is the explicit sensor-shooter handoff.
   */
  designations: Record<Side, Map<UnitId, number>>;
  /** Active jamming footprints, recomputed each turn. */
  jamming: Map<number, number>;
  /** Decoys currently deployed, presented to the enemy as false contacts. */
  decoys: Decoy[];
  objectives: Objective[];
  /** Monotonic counter for id generation; keeps ids replay-stable. */
  nextEntityId: number;
  /** Append-only log of everything that happened, for replay and AAR. */
  log: LogEntry[];
  rngState: import('./rng').RngState;
}

/**
 * A deployed decoy.
 *
 * Decoys are spawned as ordinary units with an inflated signature, no
 * weapons and a single strength step. Modelling them this way rather than as
 * a parallel entity type means every existing system — detection, targeting,
 * AI threat assessment — handles them correctly for free, and the enemy can
 * genuinely be induced to spend a missile on one.
 */
export interface Decoy {
  readonly unitId: UnitId;
  /** Turns remaining before the emitter runs down. */
  ttl: number;
}

export type LogSeverity = 'INFO' | 'CONTACT' | 'COMBAT' | 'LOSS' | 'OBJECTIVE';

export interface LogEntry {
  readonly turn: number;
  readonly side: Side;
  readonly severity: LogSeverity;
  readonly message: string;
  /** Hex the entry refers to, so the UI can focus the camera on it. */
  readonly at?: Hex;
}
